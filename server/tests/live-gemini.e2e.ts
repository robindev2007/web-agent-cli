import { GeminiBrowserProvider } from "../src/providers/gemini-browser";
import { createBridgeServer } from "../src/server/bridge";
import { AgentLoop } from "../src/agent/loop";
import { resolve } from "node:path";
import { existsSync } from "node:fs";
import { readFile, rm, mkdir } from "node:fs/promises";

const SANDBOX_DIR = resolve(process.cwd(), "test_sandbox");

async function runLiveGeminiE2ETest() {
  console.log("\n\x1b[1m\x1b[35m=== 100% REAL LIVE GEMINI E2E TEST ===\x1b[0m\n");

  // 1. Prepare clean test_sandbox folder
  if (existsSync(SANDBOX_DIR)) {
    await rm(SANDBOX_DIR, { recursive: true, force: true });
  }
  await mkdir(SANDBOX_DIR, { recursive: true });
  console.log(`\x1b[36m[Setup]\x1b[0m Sandbox prepared at: ${SANDBOX_DIR}`);

  // 2. Start Bridge Server & Real Gemini Provider
  const provider = new GeminiBrowserProvider();
  createBridgeServer(provider);

  console.log("\x1b[33m[Waiting]\x1b[0m Waiting for Chrome Extension to connect on ws://127.0.0.1:3000/ws...");
  console.log("\x1b[90m(Make sure Chrome has the extension loaded and Gemini open)\x1b[0m\n");

  // 3. Wait for real Chrome Extension WebSocket connection (up to 30s)
  const connected = await new Promise<boolean>((res) => {
    const start = Date.now();
    const interval = setInterval(() => {
      if (provider.isReady()) {
        clearInterval(interval);
        res(true);
      } else if (Date.now() - start > 30000) {
        clearInterval(interval);
        res(false);
      }
    }, 500);
  });

  if (!connected) {
    console.error("\n\x1b[31m[FAILED]: Chrome extension did not connect within 30 seconds.\x1b[0m");
    console.error("Please ensure:");
    console.error("1. Chrome is open");
    console.error("2. Extension 'Gemini Coding Agent' is reloaded in chrome://extensions");
    console.error("3. https://gemini.google.com/app is open\n");
    process.exit(1);
  }

  console.log("\x1b[32m[Connected]\x1b[0m Real Chrome extension connected! Starting live test with real Gemini Web...\n");

  // 4. Initialize AgentLoop targeting the real test_sandbox directory
  const agent = new AgentLoop(provider, SANDBOX_DIR, 8);

  const realTask =
    "Create a file named hello_real.txt containing exactly 'Generated by Live Gemini Web' and then verify it by reading the file.";

  console.log(`\x1b[35m[Task Goal]:\x1b[0m ${realTask}\n`);
  const startTime = Date.now();

  try {
    const finalSummary = await agent.runTask(realTask);
    const duration = ((Date.now() - startTime) / 1000).toFixed(1);

    console.log(`\n\x1b[32m=== LIVE E2E TEST COMPLETED (${duration}s) ===\x1b[0m`);
    console.log(`\x1b[1mFinal Summary from Real Gemini:\x1b[0m\n${finalSummary}\n`);

    // 5. Hard verification on actual disk
    const targetFile = resolve(SANDBOX_DIR, "hello_real.txt");
    if (existsSync(targetFile)) {
      const content = await readFile(targetFile, "utf-8");
      console.log(`\x1b[32m✔ VERIFIED ON DISK:\x1b[0m File exists at: ${targetFile}`);
      console.log(`\x1b[32m✔ CONTENT ON DISK:\x1b[0m "${content.trim()}"`);
      console.log("\n\x1b[32m🎉 100% REAL LIVE GEMINI E2E TEST PASSED!\x1b[0m\n");
    } else {
      console.error(`\n\x1b[31m❌ FAILED: File ${targetFile} was not found on disk.\x1b[0m\n`);
      process.exit(1);
    }
  } catch (err: any) {
    console.error(`\n\x1b[31m[Test Error]: ${err.message}\x1b[0m\n`);
    process.exit(1);
  }

  process.exit(0);
}

runLiveGeminiE2ETest();

